"""Every external command must run with stdin detached.

Why this exists
---------------
``convert_media`` hung for 180 s on a live run. The ffmpeg child was in state
``T`` (``do_signal_stop``) rather than running: ffmpeg reads stdin for its
interactive keyboard handler ("press q to stop"), and a process in a *background
process group* that reads its controlling terminal is stopped by SIGTTIN.
``subprocess.run`` then waits forever, because a stopped child never exits.

This is environment-dependent and therefore easy to miss: under systemd stdin is
``/dev/null`` so nothing blocks, but ``start.sh`` — or any manual launch from a
shell — inherits the pty, and then the tool hangs instead of failing.

The fix has two halves, both asserted here:
* ``stdin=subprocess.DEVNULL`` on the ``subprocess.run`` call, and
* ``-nostdin`` for ffmpeg (its own opt-out, belt and braces).
"""

from __future__ import annotations

import ast
import pathlib

_PKG = pathlib.Path(__file__).resolve().parents[2] / "src" / "google_search_mcp"


def _subprocess_run_calls(path: pathlib.Path):
    """Yield every ``subprocess.run(...)`` call node in *path*."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        if (
            isinstance(func, ast.Attribute)
            and func.attr == "run"
            and isinstance(func.value, ast.Name)
            and func.value.id == "subprocess"
        ):
            yield node


def test_no_subprocess_run_without_stdin_devnull():
    offenders: list[str] = []
    for path in sorted(_PKG.rglob("*.py")):
        if path.name == "server_selenium.py":
            continue  # dead code, ruff-excluded
        for call in _subprocess_run_calls(path):
            keywords = {kw.arg for kw in call.keywords}
            if "stdin" not in keywords:
                offenders.append(f"{path.relative_to(_PKG.parent.parent)}:{call.lineno}")
    assert not offenders, (
        "subprocess.run without stdin=DEVNULL can be stopped by SIGTTIN when the "
        "service was started from a shell:\n  " + "\n  ".join(offenders)
    )


def test_ffmpeg_is_invoked_with_nostdin():
    """ffmpeg's own flag, in addition to the detached stdin."""
    text = (_PKG / "tools" / "web_utils.py").read_text(encoding="utf-8")
    assert '"-nostdin"' in text, (
        "ffmpeg must be called with -nostdin so it never reads the keyboard"
    )
    assert 'cmd = ["ffmpeg", "-nostdin", "-i"' in text


def test_convert_media_does_not_hang_when_stdin_is_a_pipe(tmp_path):
    """Functional check: conversion completes with a closed stdin.

    Runs the real tool with stdin detached, which is the condition that used to
    hang. Uses a 1-second silent wav generated by ffmpeg so no fixture is needed.
    """
    import shutil
    import subprocess

    import pytest

    if shutil.which("ffmpeg") is None:  # pragma: no cover
        pytest.skip("ffmpeg not installed")

    src = tmp_path / "in.wav"
    subprocess.run(
        ["ffmpeg", "-nostdin", "-f", "lavfi", "-i", "anullsrc=r=16000:cl=mono",
         "-t", "1", str(src), "-y"],
        capture_output=True, stdin=subprocess.DEVNULL, timeout=30, check=True,
    )

    import asyncio

    from google_search_mcp.tools import web_utils

    out = asyncio.run(
        web_utils.convert_media(str(src), "mp3", output_path=str(tmp_path / "out.mp3"))
    )
    assert "Converted successfully" in out, out
    assert (tmp_path / "out.mp3").is_file()
